import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(process.env.NODE_MODULES_PATH ? path.join(process.env.NODE_MODULES_PATH, 'package.json') : new URL('../package.json', import.meta.url));
const { chromium } = require('playwright');
const root = path.resolve(fileURLToPath(new URL('../src/', import.meta.url)));
const artifacts = fileURLToPath(new URL('../test-artifacts/', import.meta.url));
const mimeTypes = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css' };
const server = createServer(async (request, response) => {
  try {
    const urlPath = decodeURIComponent(new URL(request.url, 'http://localhost').pathname);
    const filename = path.resolve(root, `.${urlPath === '/' ? '/index.html' : urlPath}`);
    if (!filename.startsWith(`${root}${path.sep}`) && filename !== root) throw new Error('Outside fixture root');
    const content = await readFile(filename);
    response.writeHead(200, { 'Content-Type': mimeTypes[path.extname(filename)] || 'application/octet-stream' });
    response.end(content);
  } catch {
    response.writeHead(404);
    response.end();
  }
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : {}) });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  const errors = [];
  const remoteRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:')) remoteRequests.push(request.url());
  });
  page.on('dialog', dialog => dialog.accept());
  const origin = `http://127.0.0.1:${server.address().port}`;
  await page.goto(`${origin}/index.html?demo=1`);
  await page.locator('#profile-basic-name').waitFor();
  await page.locator('#fill-tab').click();
  await page.locator('#scan-page').click();
  assert.match(await page.locator('#notice').textContent(), /先在.*校对并保存/);
  await page.locator('#profile-tab').click();
  await page.locator('#load-sample').click();
  assert.equal(await page.locator('#profile-basic-name').inputValue(), '林同学');
  await page.locator('#save-profile').click();
  await page.waitForFunction(() => document.querySelector('#profile-state').textContent === '已保存在本机');
  await page.locator('#go-fill').click();
  await page.locator('#scan-page').click();
  await page.waitForFunction(() => document.querySelectorAll('.field-card').length === 36);
  const matchedCount = await page.locator('.field-card input:checked').count();
  assert.ok(matchedCount >= 18, `Expected useful matches, got ${matchedCount}`);
  const cards = await page.locator('.field-card').evaluateAll(elements => elements.map(element => ({ title: element.querySelector('strong').textContent, key: element.querySelector('select').value, value: element.querySelector('textarea').value, selected: element.querySelector('input').checked })));
  const schoolCards = cards.filter(card => card.title === '学校名称');
  assert.deepEqual(schoolCards.map(card => card.value), ['示例大学', '示例中学']);
  assert.equal(cards.find(card => card.title.includes('为什么选择')).selected, false);
  assert.equal(cards.find(card => card.title.includes('虚构隐私')).selected, false);
  await page.locator('#copy-selected').click();
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /林同学/);
  await mkdir(artifacts, { recursive: true });
  await page.screenshot({ path: path.join(artifacts, 'preview.png') });
  await page.locator('#fill-selected').click();
  await page.waitForFunction(() => document.querySelector('#notice').textContent.startsWith('已填入'));
  const frame = page.frameLocator('#demo-frame');
  assert.equal(await frame.locator('#fullName').inputValue(), '林同学');
  assert.equal(await frame.locator('#phone').inputValue(), '13800000000');
  assert.equal(await frame.locator('#email').inputValue(), 'lin@example.com');
  assert.equal(await frame.locator('#gender').inputValue(), 'female');
  assert.equal(await frame.locator('#birthDate').inputValue(), '2004-05-12');
  assert.equal(await frame.locator('#school1').inputValue(), '示例大学');
  assert.equal(await frame.locator('#school2').inputValue(), '示例中学');
  assert.equal(await frame.locator('#educationStart1').inputValue(), '2023-09');
  assert.equal(await frame.locator('#educationStart2').inputValue(), '2020-09');
  assert.equal(await frame.locator('#existingValue').inputValue(), '这是网页上已经填写的内容');
  assert.equal(await frame.locator('#privacyConsent').isChecked(), false);
  assert.equal(await page.locator('#demo-frame').evaluate(element => element.contentWindow.demoSubmitCount), 0);
  await page.locator('#scan-page').click();
  await page.waitForFunction(() => document.querySelectorAll('.field-card').length === 36 && document.querySelector('#scan-page').disabled === false);
  const existingCard = page.locator('.field-card').filter({ has: page.locator('strong', { hasText: '已填内容保留测试' }) });
  assert.equal(await existingCard.locator('input[type=checkbox]').isDisabled(), true);
  await existingCard.locator('select').selectOption('basic.name');
  assert.equal(await existingCard.locator('textarea').inputValue(), '林同学');
  await existingCard.locator('button').click();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), '林同学');
  await page.locator('#allow-overwrite').check();
  await page.locator('#deselect-all').click();
  await existingCard.locator('input[type=checkbox]').check();
  await page.locator('#fill-selected').click();
  await page.waitForFunction(() => document.querySelector('#demo-frame').contentDocument.querySelector('#existingValue').value === '林同学');
  await page.locator('#profile-tab').click();
  await page.locator('#profile-basic-name').fill('林修改');
  await page.locator('#fill-tab').click();
  await page.locator('#scan-page').click();
  assert.match(await page.locator('#notice').textContent(), /校对并保存/);
  await page.reload();
  await page.locator('#profile-basic-name').waitFor();
  assert.equal(await page.locator('#profile-basic-name').inputValue(), '林同学');
  await page.locator('#resume-file').setInputFiles({ name: 'resume.txt', mimeType: 'text/plain', buffer: Buffer.from('姓名：测试同学\n手机：13900000000\n邮箱：test@example.com\n现居城市：杭州\n最高学历：本科') });
  await page.waitForFunction(() => document.querySelector('#profile-basic-name').value === '测试同学');
  assert.equal(await page.locator('#profile-basic-email').inputValue(), 'test@example.com');
  assert.match(await page.locator('#profile-state').textContent(), /请确认保存/);
  await page.locator('#save-profile').click();
  await page.waitForFunction(() => document.querySelector('#profile-state').textContent === '已保存在本机');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-profile').click();
  const download = await downloadPromise;
  const downloadedPath = await download.path();
  assert.equal(JSON.parse(await readFile(downloadedPath, 'utf8')).basic.name, '测试同学');
  await page.locator('#clear-profile').click();
  await page.waitForFunction(() => document.querySelector('#profile-basic-name').value === '');
  assert.equal(await page.evaluate(() => localStorage.getItem('resumeFillProfile')), null);
  await page.setViewportSize({ width: 380, height: 860 });
  await page.goto(`${origin}/index.html`);
  await page.locator('#profile-basic-name').waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.screenshot({ path: path.join(artifacts, 'sidebar.png'), fullPage: true });
  assert.deepEqual(errors, []);
  assert.deepEqual(remoteRequests, []);
  console.log(JSON.stringify({ passed: true, fields: 36, initiallySelected: matchedCount, checks: ['preview', 'two education entries', 'clipboard', 'selective fill', 'existing values', 'explicit overwrite', 'no submission', 'save confirmation', 'persistence', 'TXT upload', 'JSON export', 'clear', '380px layout', 'no remote requests'] }, null, 2));
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
}
